const { withMainApplication } = require('@expo/config-plugins');

const IMPORT = 'import com.teamcoach.voicechanger.VoiceChangerInstaller';
const CALL = '    VoiceChangerInstaller.install()';

// Enable MediaProjection FGS before any RN/WebRTC init. LiveKit's Expo
// lifecycle listener also calls setup() later; setting this flag early means
// voice screen share works even if that listener runs after SoLoader.
const WEBRTC_OPTIONS_IMPORT =
  'import com.oney.WebRTCModule.WebRTCModuleOptions';
const ENABLE_MEDIA_PROJECTION =
  '    WebRTCModuleOptions.getInstance().enableMediaProjectionService = true';

/**
 * Starts the local `modules/voice-changer` attach loop from
 * MainApplication.onCreate. The effect itself plugs into LiveKit's
 * `LiveKitReactNative.audioProcessingController` once WebRTC is up (LiveKit
 * owns WebRTCModuleOptions.audioProcessingFactoryFactory in 3.x).
 * Also turns on WebRTC's MediaProjection foreground service for in-call
 * screen share (Android 14+).
 * (android/ is generated by prebuild, so this can't be edited by hand.)
 */
function withVoiceChanger(config) {
  return withMainApplication(config, (cfg) => {
    let src = cfg.modResults.contents;
    if (cfg.modResults.language !== 'kt') {
      throw new Error('withVoiceChanger expects a Kotlin MainApplication (Expo SDK 50+)');
    }
    if (!src.includes(IMPORT)) {
      src = src.replace(/^(package [^\n]+\n)/m, `$1\n${IMPORT}\n`);
    }
    if (!src.includes(WEBRTC_OPTIONS_IMPORT)) {
      src = src.replace(/^(package [^\n]+\n)/m, `$1\n${WEBRTC_OPTIONS_IMPORT}\n`);
    }
    if (!src.includes('VoiceChangerInstaller.install()')) {
      src = src.replace(
        /(override fun onCreate\(\) \{\s*\n\s*super\.onCreate\(\)\s*\n)/,
        `$1${CALL}\n`,
      );
      if (!src.includes('VoiceChangerInstaller.install()')) {
        throw new Error('withVoiceChanger: could not find onCreate() in MainApplication.kt');
      }
    }
    if (!src.includes('enableMediaProjectionService = true')) {
      src = src.replace(
        /(override fun onCreate\(\) \{\s*\n\s*super\.onCreate\(\)\s*\n)/,
        `$1${ENABLE_MEDIA_PROJECTION}\n`,
      );
      if (!src.includes('enableMediaProjectionService = true')) {
        throw new Error(
          'withVoiceChanger: could not inject MediaProjection enable in MainApplication.kt',
        );
      }
    }
    cfg.modResults.contents = src;
    return cfg;
  });
}

module.exports = withVoiceChanger;
